test("design draft reloads from MongoDB and only confirmed publication changes the public storefront", async ({page}, testInfo) => {
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  const {slug, api, base} = await setup(page);
  await page.goto(`${base}/vitrin`);
  const title=page.getByLabel("Manşet Başlığı",{exact:true});
  await expect(title).toHaveValue("Commerce Browser Store");
  await title.fill("Gerçek MongoDB Vitrini");
  await page.getByRole("button", {name:"Taslağı Sakla",exact:true}).click();
  await expect(page.locator(".ad-notice")).toContainText("sunucuda saklandı");
  await page.reload(); await expect(title).toHaveValue("Gerçek MongoDB Vitrini");
  expect((await (await page.request.get(`/api/v1/public/stores/${slug}/design`)).json()).design).toBeNull();
  await expect(page.locator(".vs-preview-scroll")).toContainText("Actual Browser Product");
  await expect(page.locator(".vs-preview-scroll")).not.toContainText("Selin Y.");
  await page.getByRole("button", {name:"Değişiklikleri Yayınla",exact:false}).click();
  await page.locator("dialog[open]").getByRole("button",{name:"Yayını Onayla",exact:true}).click();
  await expect(page.locator(".ad-notice")).toContainText("Vitrin yayınlandı");
  await page.goto(`/${slug}`); await expect(page.getByRole("heading",{name:"Gerçek MongoDB Vitrini",exact:true})).toBeVisible();
  const catalogBox=await page.locator("#products").boundingBox(), aboutBox=await page.locator("#store-about").boundingBox();
  expect(catalogBox).not.toBeNull(); expect(aboutBox).not.toBeNull(); expect(aboutBox!.y).toBeGreaterThan(catalogBox!.y);
  await page.screenshot({path:testInfo.outputPath("published-storefront-desktop.png"),fullPage:true});
  await page.goto(`${base}/vitrin`); await expect(title).toHaveValue("Gerçek MongoDB Vitrini");
  await title.fill("Yayınlanmayan özel taslak");
  let failed=false;
  await page.route(`**${api}/design/draft`, async route=>{if(!failed){failed=true;await route.fulfill({status:503,contentType:"application/json",body:JSON.stringify({message:"Test save failure"})});}else await route.continue();});
  await page.getByRole("button",{name:"Taslağı Sakla",exact:true}).click();
  await expect(page.getByRole("main").locator(".vs-error[role=alert]")).toContainText("Test save failure");
  await expect(title).toHaveValue("Yayınlanmayan özel taslak");
  await page.getByRole("button",{name:"Taslağı Sakla",exact:true}).click();
  await expect(page.locator(".ad-notice")).toContainText("sunucuda saklandı");
  await page.goto(`/${slug}`); await expect(page.getByRole("heading",{name:"Gerçek MongoDB Vitrini",exact:true})).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  await expect(page.getByRole("heading",{name:"Gerçek MongoDB Vitrini",exact:true})).toBeVisible();
  await page.screenshot({path:testInfo.outputPath("published-storefront-mobile.png"),fullPage:true});
  expect(errors).toEqual([]);
});
test("invited teammate registers without creating a store and returns to the invitation", async ({page}) => {
  const {slug,api}=await setup(page), email=`storeless-invite-${randomUUID()}@example.com`;
  const invitation=await page.request.post(`${api}/team/invitations`, {headers:{Origin:origin},data:{email,role:"viewer"}});
  expect(invitation.ok()).toBeTruthy();
  const token=(await invitation.json()).token;
  await page.context().clearCookies();
  await page.goto(`/ekip-daveti?token=${token}`);
  await page.getByRole("button",{name:"Daveti Kabul Et",exact:false}).click();
  await page.getByRole("link",{name:"Mağaza açmadan kayıt ol",exact:true}).click();
  await page.getByLabel("Ad Soyad",{exact:true}).fill("Invited Viewer");
  await page.getByLabel("E-posta Adresi",{exact:true}).fill(email);
  await page.getByLabel("Şifre",{exact:true}).fill("Commerce2026!");
  await page.getByLabel("Şifre Tekrarı",{exact:true}).fill("Commerce2026!");
  await page.getByRole("button",{name:"Ücretsiz Hesap Oluştur",exact:false}).click();
  await expect(page).toHaveURL(new RegExp(`/ekip-daveti\\?token=${token}$`));
  await expect(page.getByRole("button",{name:"Daveti Kabul Et",exact:false})).toBeEnabled();
  expect((await (await page.request.get("/api/v1/auth/me")).json()).stores).toHaveLength(0);
  await page.getByRole("button",{name:"Daveti Kabul Et",exact:false}).click();
  await page.getByRole("link",{name:"Mağaza Yönetimini Aç",exact:true}).click();
  await expect(page).toHaveURL(`/${slug}/admin`);
  const me=await (await page.request.get("/api/v1/auth/me")).json();
  expect(me.stores).toHaveLength(1); expect(me.stores[0].slug).toBe(slug);
  const denied=await page.request.post(`${api}/orders`,{headers:{Origin:origin},data:{}});
  expect([404,422]).toContain(denied.status());
});
