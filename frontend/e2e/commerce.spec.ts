import { test, expect, type Page } from "@playwright/test";
import { randomUUID } from "node:crypto";
const origin = "http://localhost:3010";
async function setup(page: Page) {
  const registered = await page.request.post("/api/v1/auth/register", {headers: {Origin: origin}, data: {name: "Commerce Browser Owner", email: `commerce-browser-${randomUUID()}@example.com`, password: "Commerce2026!", store: "Commerce Browser Store"}});
  expect(registered.ok()).toBeTruthy();
  const slug = (await registered.json()).stores[0].slug;
  const api = `/api/v1/stores/${slug}`, base = `/${slug}/admin`;
  const settings = await (await page.request.get(api)).json();
  const {id: _id, ...values} = settings;
  expect((await page.request.put(`${api}/settings`, {headers: {Origin: origin}, data: {...values, isOpen: true}})).ok()).toBeTruthy();
  const product = await page.request.post(`${api}/products`, {headers: {Origin: origin}, data: {name: "Actual Browser Product", category: "Giyim", description: "Gerçek ürün açıklaması", sku: randomUUID(), barcode: "", priceCents: 12345, costCents: 3000, currency: "TRY", stock: 8, variants: ["M"], images: ["/dropshipping/cardigan.jpg"], status: "live", model: "own", seoTitle: "", seoDescription: ""}});
  expect(product.ok()).toBeTruthy();
  return {slug, api, base, product: await product.json()};
}
